// Writes `src/fonts.generated.ts` from the Fontsource packages: one entry for each subset
// file of each font, with its `unicode-range`. `next/font/google` makes the same list for the
// Next.js build.
import fs from 'node:fs';
import path from 'node:path';

const projectRoot = path.resolve(import.meta.dirname, '..');

const FONTS = [
  { family: 'Inter', packageName: '@fontsource-variable/inter' },
  { family: 'JetBrains Mono', packageName: '@fontsource-variable/jetbrains-mono' },
];

const entries = [];
for (const { family, packageName } of FONTS) {
  const css = fs.readFileSync(
    path.join(projectRoot, 'node_modules', packageName, 'index.css'),
    'utf8'
  );
  for (const [, subset, body] of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{(.*?)\}/gs)) {
    const file = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
    const weight = body.match(/font-weight: ([^;]+);/)[1];
    const unicodeRange = body.match(/unicode-range: ([^;]+);/)[1];
    const isLatin = /-latin-wght-normal$/.test(subset);
    entries.push(
      [
        '  {',
        `    family: ${JSON.stringify(family)},`,
        `    weight: ${JSON.stringify(weight)},`,
        `    unicodeRange: ${JSON.stringify(unicodeRange)},`,
        `    isPreloaded: ${isLatin},`,
        `    source: require('${packageName}/files/${file}'),`,
        '  },',
      ].join('\n')
    );
  }
}

fs.writeFileSync(
  path.join(projectRoot, 'src/fonts.generated.ts'),
  [
    '// Generated by scripts/generate-fonts.mjs. Do not edit.',
    'export const FONT_FACES = [',
    ...entries,
    '];',
    '',
  ].join('\n')
);
console.log(`Generated ${entries.length} font faces in src/fonts.generated.ts`);
