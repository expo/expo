/**
 * Links a module whose checked-in Package.swift depends on the ExpoModulesCoreHeaders
 * product through that manifest instead of a generated one. It names its Expo dependencies by
 * paths relative to `<outDir>/direct/<package>`, so this writes those neighbours:
 *
 *   direct/<package>                 → relative symlink to the module root
 *   direct/ExpoModulesCoreHeaders    → compile-only ExpoModulesCore: a relative symlink to its
 *                                      prebuilt headers xcframework, plus a dependency on the
 *                                      ExpoModulesJSI headers package the plugin emits
 *   $BUILD_DIR/ExpoModulesMacros     → relative symlink to the prebuilt macro plugin; the
 *                                      manifest names it as `${BUILD_DIR}/ExpoModulesMacros`
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { runDumpPackage } = require('./cli');
const { pluginError, rerunSpmUpdate } = require('./diagnostics');

const CORE_HEADERS = 'ExpoModulesCoreHeaders';
const JSI_HEADERS = 'ExpoModulesJSIHeaders';
// A binary target cannot have dependencies, so this source target carries the JSI one.
const CORE_HEADERS_DEPENDENCIES = 'ExpoModulesCoreHeadersDependencies';
// Written into the package by an earlier generator; nothing reads it now.
const LEGACY_STUBS_DIR = '.stubs';

/**
 * Whether a dumped manifest compiles against ExpoModulesCoreHeaders, which only a manifest
 * written to be built as it stands can name. A `byName` dependency counts: SwiftPM resolves
 * it to that product when no target of the package has the name.
 */
function dependsOnCoreHeaders(manifest) {
  return (manifest.targets ?? []).some((target) =>
    (target.dependencies ?? []).some(
      (dependency) => (dependency.product ?? dependency.byName)?.[0] === CORE_HEADERS
    )
  );
}

/**
 * Module manifests depend on the product, so it keeps the package's name. ExpoModulesCore's
 * interface re-exports ExpoModulesJSI, so the product brings the JSI headers package along;
 * it must not declare a JSI headers target of its own, because SwiftPM rejects two targets
 * of one name in a graph.
 */
function coreHeadersManifest(jsiHeadersPkgRelativePath) {
  return `// swift-tools-version: 6.0
// AUTO-GENERATED by expo/scripts/spm/direct.js — do not edit.
// Compile-only ExpoModulesCore. The runtime framework is linked and embedded by React
// Native outside SwiftPM.
import PackageDescription

let package = Package(
    name: "${CORE_HEADERS}",
    products: [
        .library(name: "${CORE_HEADERS}", targets: ["${CORE_HEADERS}", "${CORE_HEADERS_DEPENDENCIES}"]),
    ],
    dependencies: [
        .package(name: "${JSI_HEADERS}", path: "${jsiHeadersPkgRelativePath}"),
    ],
    targets: [
        .binaryTarget(name: "${CORE_HEADERS}", path: "${CORE_HEADERS}.xcframework"),
        .target(
            name: "${CORE_HEADERS_DEPENDENCIES}",
            dependencies: [.product(name: "${JSI_HEADERS}", package: "${JSI_HEADERS}")],
            path: "${CORE_HEADERS_DEPENDENCIES}"
        ),
    ]
)
`;
}

function relativeSymlink(target, link) {
  const relative = path.relative(path.dirname(link), target);
  try {
    if (fs.readlinkSync(link) === relative) return;
  } catch {}
  fs.rmSync(link, { recursive: true, force: true });
  fs.symlinkSync(relative, link);
}

function writeIfChanged(file, contents) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === contents) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

function emitCoreHeadersPackage(directDir, coreHeadersXCFramework, jsiHeadersPkgPath) {
  const pkgDir = path.join(directDir, CORE_HEADERS);
  fs.mkdirSync(pkgDir, { recursive: true });
  fs.rmSync(path.join(pkgDir, LEGACY_STUBS_DIR), { recursive: true, force: true });
  relativeSymlink(coreHeadersXCFramework, path.join(pkgDir, `${CORE_HEADERS}.xcframework`));
  writeIfChanged(
    path.join(pkgDir, CORE_HEADERS_DEPENDENCIES, `${CORE_HEADERS_DEPENDENCIES}.swift`),
    ''
  );
  writeIfChanged(
    path.join(pkgDir, 'Package.swift'),
    coreHeadersManifest(path.relative(pkgDir, jsiHeadersPkgPath))
  );
}

/**
 * Wire one module through its own checked-in manifest. Returns the emission shape
 * `manifests.js#emitPackage` returns, so the plugin links it like any manifest package.
 *
 * @param jsiHeadersPkgPath the ExpoModulesJSI headers package the plugin emits, or null when
 *   expo-modules-jsi is not autolinked.
 * @param manifest the module's manifest, as `dumpModuleManifest` parsed it.
 */
function emitDirectPackage({
  moduleRoot,
  packageName,
  outDir,
  coreHeadersXCFramework,
  jsiHeadersPkgPath,
  macroTool,
  manifest,
}) {
  if (jsiHeadersPkgPath == null) {
    throw pluginError({
      what: `${packageName} is built from its own Package.swift and needs the ExpoModulesJSI headers, but expo-modules-jsi is not autolinked.`,
      why: 'The ExpoModulesCore headers it compiles against re-export ExpoModulesJSI.',
      how: `expo-modules-core depends on expo-modules-jsi, so reinstall your JavaScript dependencies, and remove expo-modules-jsi from \`"expo": { "autolinking": { "exclude": [...] } }\` in your package.json if it is listed there. ${rerunSpmUpdate()}`,
    });
  }
  const directDir = path.join(outDir, 'direct');
  fs.mkdirSync(directDir, { recursive: true });
  emitCoreHeadersPackage(directDir, coreHeadersXCFramework, jsiHeadersPkgPath);
  const macroLink = macroPluginLink();
  if (macroLink) {
    fs.mkdirSync(path.dirname(macroLink), { recursive: true });
    relativeSymlink(macroTool, macroLink);
  }
  const link = path.join(directDir, packageName);
  fs.mkdirSync(path.dirname(link), { recursive: true });
  relativeSymlink(moduleRoot, link);
  fs.rmSync(path.join(outDir, 'expo-source', manifest.name), { recursive: true, force: true });

  return {
    ok: {
      packageDep: { name: manifest.name, path: link },
      productDeps: manifest.products.map((p) => ({ name: p.name, package: manifest.name })),
      spmProductNames: [],
      partlyProvidedPackages: [],
    },
  };
}

/**
 * `swift package dump-package` of the checked-in manifest at `moduleRoot`: the JSON the
 * tool printed, and its parse.
 */
function dumpModuleManifest(moduleRoot, packageName) {
  try {
    const json = runDumpPackage(moduleRoot);
    return { json, manifest: JSON.parse(json) };
  } catch (error) {
    throw pluginError(
      {
        what: `${packageName}'s Package.swift could not be evaluated: ${dumpFailureDetail(error)}.`,
        why: `${packageName} is built from source, so the plugin reads its manifest with \`swift package dump-package\` to decide how to build it and to find the products it exports.`,
        how: `Fix the Package.swift in ${moduleRoot}; run \`swift package dump-package\` in that folder to see the full error. If the swift command is missing, install Xcode and select its command line tools with \`sudo xcode-select --switch /Applications/Xcode.app\`. ${rerunSpmUpdate()}`,
      },
      { cause: error }
    );
  }
}

function dumpFailureDetail(error) {
  if (error.code === 'ENOENT') return 'the swift command was not found';
  const output =
    typeof error.stderr === 'string' && error.stderr.trim() ? error.stderr : error.message;
  return output.trim().split('\n')[0];
}

function macroPluginLink() {
  return process.env.BUILD_DIR ? path.join(process.env.BUILD_DIR, 'ExpoModulesMacros') : null;
}

// Far enough ahead that every later sync stamp is older.
const PENDING_MARKER_MTIME = new Date('2100-01-01T00:00:00Z');

/**
 * Only a sync inside a build knows BUILD_DIR, so only it can create the macro plugin link.
 * RN re-syncs in the build when a watched path has vanished or is newer than its stamp,
 * and drops watched paths that do not exist.
 * - In a build: watch the link, since Clean Build Folder deletes it but keeps the stamp.
 * - Outside a build: the link cannot be made, yet the stamp is fresh. Watch a marker
 *   dated in the future, so the next build always re-syncs; that sync removes it.
 */
function prepareDirectWatchPaths(directPackages, outDir) {
  const marker = path.join(outDir, 'direct', '.macro-plugin-link-pending');
  const macroLink = macroPluginLink();
  const hasDirect = directPackages.length > 0;
  if (!hasDirect || macroLink) {
    fs.rmSync(marker, { force: true });
    return hasDirect ? [macroLink] : [];
  }
  if (fs.statSync(marker, { throwIfNoEntry: false })?.mtimeMs !== PENDING_MARKER_MTIME.getTime()) {
    fs.mkdirSync(path.dirname(marker), { recursive: true });
    fs.writeFileSync(marker, '');
    fs.utimesSync(marker, PENDING_MARKER_MTIME, PENDING_MARKER_MTIME);
  }
  return [marker];
}

module.exports = {
  dependsOnCoreHeaders,
  dumpModuleManifest,
  emitDirectPackage,
  prepareDirectWatchPaths,
};
