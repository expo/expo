import fs from 'fs/promises';
import path from 'path';

type ShortcutConfig = {
  phrases: string[];
  shortTitle?: string;
  systemImageName?: string;
};

export type IntentConfig = ShortcutConfig &
  (
    | { name: string; swiftType?: never; title?: string; dialog?: string; openAppWhenRun?: boolean }
    | { swiftType: string; name?: never; title?: never; dialog?: never; openAppWhenRun?: never }
  );

const FILE = 'GeneratedIntents.swift';
const HEADER = '// Generated by expo-app-intents from the plugin configuration. Do not edit.\n';
const RESERVED = new Set(['GeneratedIntents', 'GeneratedAppShortcuts']);
const KEYWORDS = new Set(
  'associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while as Any false is nil self Self super throws true try _'.split(
    ' '
  )
);

function fail(message: string): never {
  throw new Error(`expo-app-intents: ${message}`);
}

function identifier(value: unknown): asserts value is string {
  if (typeof value !== 'string' || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(value) || KEYWORDS.has(value)) {
    fail(
      `Invalid Swift identifier '${String(value)}'. Use letters, digits and underscores, starting with a letter or underscore, and avoid Swift keywords.`
    );
  }
}

// Escape Swift interpolation as well as ordinary string delimiters. JSON escaping is not Swift escaping.
function literal(value: string): string {
  return (
    '"' +
    // eslint-disable-next-line no-control-regex -- Control characters need Swift Unicode escapes.
    value.replace(/[\\"\u0000-\u001f\u007f]/g, (char) => {
      if (char === '\\' || char === '"') return '\\' + char;
      return `\\u{${char.charCodeAt(0).toString(16)}}`;
    }) +
    '"'
  );
}

function title(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/_/g, ' ')
    .replace(/^./, (c) => c.toUpperCase());
}

function typeName(entry: IntentConfig): string {
  return entry.swiftType ?? `Generated${entry.name![0].toUpperCase()}${entry.name!.slice(1)}Intent`;
}

export function renderIntents(intents: IntentConfig[]): string {
  if (!Array.isArray(intents) || intents.length > 10)
    fail('intents must be an array with at most 10 App Shortcuts.');
  const types = new Set(RESERVED);
  for (const entry of intents) {
    if (
      !entry ||
      typeof entry !== 'object' ||
      (entry.name !== undefined) === (entry.swiftType !== undefined)
    ) {
      fail('Each intent must declare exactly one of name or swiftType.');
    }
    identifier(entry.name ?? entry.swiftType);
    const type = typeName(entry);
    if (types.has(type)) fail(`Duplicate or reserved Swift type '${type}'.`);
    types.add(type);
    if (
      !Array.isArray(entry.phrases) ||
      !entry.phrases.length ||
      entry.phrases.some((p) => typeof p !== 'string' || !p.includes('{appName}'))
    ) {
      fail(`Every phrase for '${type}' must contain {appName}; provide at least one phrase.`);
    }
    for (const field of ['title', 'shortTitle', 'dialog', 'systemImageName'] as const) {
      if (entry[field] !== undefined && (typeof entry[field] !== 'string' || !entry[field].trim()))
        fail(`${field} must be a non-empty string.`);
    }
    if (entry.openAppWhenRun !== undefined && typeof entry.openAppWhenRun !== 'boolean')
      fail('openAppWhenRun must be a boolean.');
    if (
      entry.swiftType !== undefined &&
      ['title', 'dialog', 'openAppWhenRun'].some((key) => key in entry)
    )
      fail(
        'swiftType entries cannot configure title, dialog or openAppWhenRun; configure those in Swift.'
      );
  }
  if (!intents.length) return '';
  const definitions = intents
    .filter((entry) => entry.name !== undefined)
    .map(
      (entry) => `struct ${typeName(entry)}: AppIntent {
  static let title: LocalizedStringResource = ${literal(entry.title ?? title(entry.name!))}
  static let openAppWhenRun: Bool = ${entry.openAppWhenRun ?? true}

  @MainActor
  func perform() async throws -> some IntentResult${entry.dialog === undefined ? '' : ' & ProvidesDialog'} {
    await AppIntentDispatcher.shared.dispatch(name: ${literal(entry.name!)})
    return .result(${entry.dialog === undefined ? '' : `dialog: ${literal(entry.dialog)}`})
  }
}`
    )
    .join('\n\n');
  const shortcuts = intents
    .map(
      (entry) => `    AppShortcut(
      intent: ${typeName(entry)}(),
      phrases: [${entry.phrases
        .map((phrase) =>
          phrase
            .split('{appName}')
            .map((part) => literal(part).slice(1, -1))
            .join('\\(.applicationName)')
        )
        .map((phrase) => '"' + phrase + '"')
        .join(', ')}],
      shortTitle: ${literal(entry.shortTitle ?? entry.title ?? title(entry.name ?? entry.swiftType!))},
      systemImageName: ${literal(entry.systemImageName ?? 'sparkles')}
    )`
    )
    .join('\n');
  return `${HEADER}// Run npx expo prebuild to regenerate.
import AppIntents
internal import ExpoAppIntents
internal import ExpoModulesCore

${definitions}

struct GeneratedAppShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
${shortcuts}
  }
}

// Inline Modules discovers Module classes by their matching filename.
final class GeneratedIntents: Module {
  public func definition() -> ExpoModulesCore.ModuleDefinition {
    Name("GeneratedIntents")
    OnCreate {
      Task {
        await AppIntentDispatcher.shared.setShortcutsRefreshHandler {
          GeneratedAppShortcuts.updateAppShortcutParameters()
        }
        GeneratedAppShortcuts.updateAppShortcutParameters()
      }
    }
  }
}
`;
}

async function readOptional(file: string): Promise<string | undefined> {
  try {
    return await fs.readFile(file, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

async function swiftSources(directory: string): Promise<string[]> {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await swiftSources(file)));
    else if (entry.isFile() && entry.name.endsWith('.swift')) files.push(file);
  }
  return files;
}

export async function syncIntents(
  projectRoot: string,
  directory: string,
  intents?: IntentConfig[]
): Promise<void> {
  const folder = path.resolve(projectRoot, directory);
  const file = path.join(folder, FILE);
  const previous = await readOptional(file);
  const contents = intents === undefined ? '' : renderIntents(intents);
  if (!contents) {
    if (previous?.startsWith(HEADER)) await fs.unlink(file);
    return;
  }
  if (previous !== undefined && !previous.startsWith(HEADER))
    fail(`Refusing to overwrite user-owned ${file}. Move or rename it first.`);
  await fs.mkdir(folder, { recursive: true });
  const generatedTypes = [
    ...RESERVED,
    ...intents!.filter((entry) => entry.name !== undefined).map(typeName),
  ];
  for (const source of await swiftSources(folder)) {
    if (source === file) continue;
    const text = await fs.readFile(source, 'utf8');
    // Conservative source check: compilation remains authoritative for Swift declarations.
    if (/\bAppShortcutsProvider\b|\bsetShortcutsRefreshHandler\b/.test(text))
      fail(
        `${source} contains a shortcuts provider or refresh handler. Config mode owns the provider; migrate its entries to intents and remove the old provider/refresh wiring.`
      );
    for (const name of generatedTypes) {
      if (new RegExp(`\\b(?:class|struct|enum|actor|typealias|protocol)\\s+${name}\\b`).test(text))
        fail(`Generated type '${name}' conflicts with ${source}. Rename the user type or intent.`);
    }
  }
  if (contents !== previous) await fs.writeFile(file, contents);
}
