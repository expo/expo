import type { ExpoConfig } from 'expo/config';
import type { ConfigPlugin } from 'expo/config-plugins';
import { WarningAggregator, withAppDelegate, withInfoPlist } from 'expo/config-plugins';
import resolveFrom from 'resolve-from';
import semver from 'semver';

import type { PluginConfigType } from './pluginConfig';

const PROPERTY_NAME = 'ios.enableSceneSupport';
/** The first SDK 57 patch that ships `ExpoAppSceneDelegate` and `ExpoReactNativeFactoryProvider`. */
const MINIMUM_EXPO_VERSION = '57.0.23';
/** SDK 58 and newer adopt the scene lifecycle in the project template. */
const NATIVE_SUPPORT_SDK_MAJOR = 58;

const ORIGINAL_APP_DELEGATE = 'class AppDelegate: ExpoAppDelegate {';
const SCENE_APP_DELEGATE = 'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {';
const FACTORY_ASSIGNMENT = '    reactNativeFactory = factory';
const WINDOW_ASSIGNMENT = '    window = UIWindow(frame: UIScreen.main.bounds)';
const START_REACT_NATIVE = `    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)`;

// These markers keep the exact locations of the Expo-owned startup statements. This lets the
// plugin preserve code inserted by other config plugins and restore the original file precisely.
const WINDOW_ASSIGNMENT_MARKER =
  '    // @generated by expo-build-properties: ios.enableSceneSupport window assignment';
const START_REACT_NATIVE_MARKER =
  '    // @generated by expo-build-properties: ios.enableSceneSupport React Native startup';
const MARKED_WRAPPED_STARTUP = `#if os(iOS) || os(tvOS)
${WINDOW_ASSIGNMENT_MARKER}
${START_REACT_NATIVE_MARKER}
#endif
`;
const LEGACY_WRAPPED_STARTUP = `#if os(iOS) || os(tvOS)
${WINDOW_ASSIGNMENT}
${START_REACT_NATIVE}
#endif
`;

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default Configuration',
        UISceneDelegateClassName: 'EXExpoAppSceneDelegate',
      },
    ],
  },
};

/**
 * Adopts the UIKit scene lifecycle in SDK 57 projects when `ios.enableSceneSupport` is set.
 * SDK 58 and newer include scene support in the template, so the property is a no-op there.
 */
export const withIosSceneSupport: ConfigPlugin<PluginConfigType> = (config, props) => {
  const enabled = props.ios?.enableSceneSupport;
  if (enabled === undefined) {
    return config;
  }

  const expoVersion = getExpoVersion(config);
  if (expoVersion && semver.major(expoVersion) >= NATIVE_SUPPORT_SDK_MAJOR) {
    WarningAggregator.addWarningIOS(
      PROPERTY_NAME,
      `Expo SDK 58 and newer include UIKit scene lifecycle support. \`${PROPERTY_NAME}\` is no longer required and can be removed from the expo-build-properties config.`
    );
    return config;
  }
  if (!expoVersion || semver.lt(expoVersion, MINIMUM_EXPO_VERSION)) {
    throw new Error(
      `\`${PROPERTY_NAME}\` requires Expo SDK ${MINIMUM_EXPO_VERSION} or a newer SDK 57 patch (received ${JSON.stringify(expoVersion ?? 'unknown')}).`
    );
  }

  config = withAppDelegate(config, (config) => {
    if (config.modResults.language !== 'swift') {
      throw new Error(`\`${PROPERTY_NAME}\` requires the standard Expo SDK 57 Swift AppDelegate.`);
    }
    config.modResults.contents = updateAppDelegate(config.modResults.contents, enabled);
    return config;
  });

  return withInfoPlist(config, (config) => {
    const manifest = config.modResults.UIApplicationSceneManifest;
    if (enabled) {
      if (manifest !== undefined && !isOwnedManifest(manifest)) {
        throw new Error(
          `\`${PROPERTY_NAME}\` cannot enable scene support because UIApplicationSceneManifest is already declared by the app.`
        );
      }
      config.modResults.UIApplicationSceneManifest = SCENE_MANIFEST;
    } else if (isOwnedManifest(manifest)) {
      delete config.modResults.UIApplicationSceneManifest;
    }
    return config;
  });
};

/**
 * Resolve the installed `expo` version. `config.sdkVersion` only carries the SDK major
 * (for example `57.0.0`), so the installed package is needed for the patch-level check.
 */
function getExpoVersion(config: Pick<ExpoConfig, 'sdkVersion' | '_internal'>): string | undefined {
  const projectRoot = config._internal?.projectRoot;
  const expoPackageJsonPath = projectRoot && resolveFrom.silent(projectRoot, 'expo/package.json');
  const installedVersion: unknown = expoPackageJsonPath && require(expoPackageJsonPath).version;
  const version = typeof installedVersion === 'string' ? installedVersion : config.sdkVersion;
  return version && semver.valid(version) ? version : undefined;
}

function isOwnedManifest(manifest: unknown): boolean {
  return JSON.stringify(manifest) === JSON.stringify(SCENE_MANIFEST);
}

function updateAppDelegate(contents: string, enabled: boolean): string {
  const originalClassCount = countStandaloneOccurrences(contents, ORIGINAL_APP_DELEGATE);
  const sceneClassCount = countStandaloneOccurrences(contents, SCENE_APP_DELEGATE);
  const factoryAssignmentCount = countStandaloneOccurrences(contents, FACTORY_ASSIGNMENT);
  const windowAssignmentCount = countStandaloneOccurrences(contents, WINDOW_ASSIGNMENT);
  const startReactNativeCount = countStandaloneOccurrences(contents, START_REACT_NATIVE);
  const windowMarkerCount = countStandaloneOccurrences(contents, WINDOW_ASSIGNMENT_MARKER);
  const startMarkerCount = countStandaloneOccurrences(contents, START_REACT_NATIVE_MARKER);

  if (enabled) {
    const alreadyEnabled =
      originalClassCount === 0 &&
      sceneClassCount === 1 &&
      factoryAssignmentCount === 1 &&
      windowAssignmentCount === 0 &&
      startReactNativeCount === 0 &&
      windowMarkerCount === 1 &&
      startMarkerCount === 1;
    if (alreadyEnabled) {
      return contents;
    }

    // `enableSceneSupport` initially removed the whole startup block. Add markers to that
    // previously generated shape so projects can move to the reversible representation.
    const previouslyEnabled =
      originalClassCount === 0 &&
      sceneClassCount === 1 &&
      factoryAssignmentCount === 1 &&
      windowAssignmentCount === 0 &&
      startReactNativeCount === 0 &&
      windowMarkerCount === 0 &&
      startMarkerCount === 0;
    if (previouslyEnabled) {
      const insertionPoint = `${FACTORY_ASSIGNMENT}\n\n`;
      if (!contents.includes(insertionPoint)) {
        throwInvalidAppDelegate();
      }
      return contents.replace(
        insertionPoint,
        `${FACTORY_ASSIGNMENT}\n\n${MARKED_WRAPPED_STARTUP}\n`
      );
    }

    const isLegacyTemplate =
      originalClassCount === 1 &&
      sceneClassCount === 0 &&
      factoryAssignmentCount === 1 &&
      windowAssignmentCount === 1 &&
      startReactNativeCount === 1 &&
      windowMarkerCount === 0 &&
      startMarkerCount === 0;
    if (!isLegacyTemplate) {
      throwInvalidAppDelegate();
    }

    let updated = replaceStandaloneOccurrence(contents, ORIGINAL_APP_DELEGATE, SCENE_APP_DELEGATE);
    updated = replaceStandaloneOccurrence(updated, WINDOW_ASSIGNMENT, WINDOW_ASSIGNMENT_MARKER);
    return replaceStandaloneOccurrence(updated, START_REACT_NATIVE, START_REACT_NATIVE_MARKER);
  }

  const alreadyDisabled =
    originalClassCount === 1 &&
    sceneClassCount === 0 &&
    factoryAssignmentCount === 1 &&
    windowAssignmentCount === 1 &&
    startReactNativeCount === 1 &&
    windowMarkerCount === 0 &&
    startMarkerCount === 0;
  if (alreadyDisabled) {
    return contents;
  }

  // Preserve the rollback behavior for projects generated by the initial implementation,
  // which removed the startup block before the reversible markers existed.
  const previouslyEnabled =
    originalClassCount === 0 &&
    sceneClassCount === 1 &&
    factoryAssignmentCount === 1 &&
    windowAssignmentCount === 0 &&
    startReactNativeCount === 0 &&
    windowMarkerCount === 0 &&
    startMarkerCount === 0;
  if (previouslyEnabled) {
    const insertionPoint = `${FACTORY_ASSIGNMENT}\n\n`;
    if (!contents.includes(insertionPoint)) {
      throwInvalidAppDelegate();
    }
    const updated = replaceStandaloneOccurrence(
      contents,
      SCENE_APP_DELEGATE,
      ORIGINAL_APP_DELEGATE
    );
    return updated.replace(insertionPoint, `${FACTORY_ASSIGNMENT}\n\n${LEGACY_WRAPPED_STARTUP}\n`);
  }

  const isOwnedSceneTemplate =
    originalClassCount === 0 &&
    sceneClassCount === 1 &&
    factoryAssignmentCount === 1 &&
    windowAssignmentCount === 0 &&
    startReactNativeCount === 0 &&
    windowMarkerCount === 1 &&
    startMarkerCount === 1;
  if (!isOwnedSceneTemplate) {
    throwInvalidAppDelegate();
  }

  let updated = replaceStandaloneOccurrence(contents, SCENE_APP_DELEGATE, ORIGINAL_APP_DELEGATE);
  updated = replaceStandaloneOccurrence(updated, WINDOW_ASSIGNMENT_MARKER, WINDOW_ASSIGNMENT);
  return replaceStandaloneOccurrence(updated, START_REACT_NATIVE_MARKER, START_REACT_NATIVE);
}

function countStandaloneOccurrences(contents: string, value: string): number {
  return contents.match(getStandaloneOccurrenceRegex(value, 'gm'))?.length ?? 0;
}

function replaceStandaloneOccurrence(contents: string, value: string, replacement: string): string {
  return contents.replace(getStandaloneOccurrenceRegex(value, 'm'), replacement);
}

function getStandaloneOccurrenceRegex(value: string, flags: string): RegExp {
  const escaped = value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`^${escaped}(?=\\r?$)`, flags);
}

function throwInvalidAppDelegate(): never {
  throw new Error(`\`${PROPERTY_NAME}\` requires the standard Expo SDK 57 Swift AppDelegate.`);
}
