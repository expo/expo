// @ref llp/0006-agent-native-cli-surface.rfc.md §AGENTS.md generation
// The body of the managed block: the project facts an agent would otherwise guess at, and the
// commands that answer in a shape it can parse. Pure text generation — no I/O, no timestamps, so
// the same project always produces the same block and a rerun rewrites nothing.
import type { ProjectState } from '../project/types';

export interface AgentsMdContext {
  /** The probed project state, from `probeProjectStateAsync`. */
  state: ProjectState;
  /** `name` of the project's `package.json`, or null when it has none. */
  projectName: string | null;
  /** Project-relative skills directories of the targeted agents, e.g. `[".claude/skills"]`. */
  skillsDirs: string[];
}

/** Render the body of the managed block, without the markers around it. */
export function generateAgentsMdBlock({ state, projectName, skillsDirs }: AgentsMdContext): string {
  return [
    '<!-- Generated by `npx exagent agents:setup`. Everything inside the markers is overwritten on the next run. -->',
    '',
    '## Expo project',
    '',
    `- Project: ${projectName ?? 'unnamed (no name in package.json)'}`,
    `- SDK: ${state.sdkVersion ?? 'unknown (the `expo` package is not installed)'}`,
    `- Native: ${nativeLine(state)}`,
    `- Expo Go: ${expoGoLine(state)}`,
    `- Dev client: \`expo-dev-client\` is ${state.usesDevClient ? 'installed' : 'not installed'}`,
    '',
    '## Commands',
    '',
    'Prefer these over the raw `expo` commands: they answer in a shape an agent can parse, and most of them take `--json` for the machine-readable form.',
    '',
    '- `npx exagent status` — where the project is right now, and what would happen next',
    '- `npx exagent status --json` — the same report as one object, with the raw project probe under `probe`',
    '- `npx exagent status --explain` — the deep dive: which sources changed, whether an update can ship over the air, and whether EAS already has a build for this fingerprint',
    '- `npx exagent status --assert js-only` — a gate on what a change costs: exit 20 when it costs more than the class named, 22 when nothing could be measured, 0 otherwise',
    '- `npx exagent dev` — get the app onto a device: it prints the plan, then runs it; `npx exagent dev --plan` prints the steps without running them',
    '- `npx exagent start` — `expo start` and nothing else: a dev server no planning may touch',
    '- `npx exagent install <pkg>` — install a package and report what it changes natively',
    '- `npx exagent typecheck` — run the TypeScript compiler of this project as a gate: exit 20 with the diagnostics, exit 0 when there are none. A bundle that builds and an app that does not throw do not cover this.',
    '- `npx exagent runtime:eval <js>` — evaluate JavaScript in the running app',
    '- `npx exagent runtime:errors` — collect the runtime errors of the running app',
    '- `npx exagent navigate <route>` — open a route as a deep link on a device',
    '- `npx exagent skills:list` — the agent skills the installed packages ship',
    '- `npx exagent new <dir>` / `npx exagent deploy` — create a project headlessly / deploy web and native',
    '- `npx exagent checkpoint:undo` — restore the last checkpoint taken before a mutating command',
    '',
    skillsLine(skillsDirs),
  ].join('\n');
}

function nativeLine(state: ProjectState): string {
  const checkedIn = [state.nativeDirs.ios && 'ios', state.nativeDirs.android && 'android'].filter(
    Boolean
  );
  if (checkedIn.length) {
    return `bare (${checkedIn.join(', ')} checked into the repo, so they are the source of truth)`;
  }
  return 'CNG (no native directories; they are generated by `npx expo prebuild`)';
}

function expoGoLine(state: ProjectState): string {
  if (state.expoGo.compatible) {
    return 'compatible (Expo Go can run this project)';
  }
  const count = state.expoGo.reasons.length;
  return `not compatible (${count} reason${count === 1 ? '' : 's'}; needs a development build, run \`npx exagent status --json\` for the details)`;
}

function skillsLine(skillsDirs: string[]): string {
  if (!skillsDirs.length) {
    return 'No agent skills are linked yet. Run `npx exagent agents:setup --agent <agent>` to link the skills the installed packages ship.';
  }
  return `Agent skills of the installed packages are linked into ${skillsDirs
    .map((dir) => `\`${dir}\``)
    .join(', ')}. Rerun \`npx exagent agents:setup\` after installing a package.

Commands end with a \`Suggested next:\` section — suggested follow-up commands, not required steps. Run one only when it serves your current goal.`;
}
