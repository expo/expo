import plist from '@expo/plist';
import { ConfigPlugin, withDangerousMod } from 'expo/config-plugins';
import fs from 'node:fs';
import path from 'node:path';

/**
 * The ExtensionKit extension point the system uses to find crash reporter extensions.
 */
export const EXTENSION_POINT_IDENTIFIER = 'com.apple.crash-reporter.extension';

type CrashReporterExtensionFilesProps = {
  targetName: string;
};

/**
 * Writes the extension's source files to `ios/<targetName>/`. The files are generated, so they are
 * overwritten on every prebuild.
 */
const withCrashReporterExtensionFiles: ConfigPlugin<CrashReporterExtensionFilesProps> = (
  config,
  { targetName }
) =>
  withDangerousMod(config, [
    'ios',
    async (config) => {
      await writeExtensionFiles(config.modRequest.platformProjectRoot, targetName);
      return config;
    },
  ]);

export default withCrashReporterExtensionFiles;

export async function writeExtensionFiles(platformProjectRoot: string, targetName: string) {
  const directory = path.join(platformProjectRoot, targetName);
  await fs.promises.mkdir(directory, { recursive: true });
  await fs.promises.writeFile(path.join(directory, 'Info.plist'), buildInfoPlist());
  await fs.promises.writeFile(
    path.join(directory, `${targetName}.swift`),
    buildExtensionSource(targetName)
  );
}

/**
 * Only the keys Xcode cannot generate. The target sets `GENERATE_INFOPLIST_FILE`, so Xcode adds
 * the bundle identifier, versions and other standard keys at build time.
 */
export function buildInfoPlist(): string {
  return plist.build({
    EXAppExtensionAttributes: {
      EXExtensionPointIdentifier: EXTENSION_POINT_IDENTIFIER,
    },
  });
}

export function buildExtensionSource(typeName: string): string {
  return `// Generated by expo-observe. Do not edit, changes are overwritten on prebuild.

#if canImport(CrashReportExtension)
import CrashReportExtension
import ExtensionFoundation

@main
struct ${typeName}: CrashReporterExtension {
  func processCrashReport(process: CrashedProcess) {}
}
#else
// The CrashReportExtension framework ships only in the iOS device SDK. This stub keeps the target
// building for the simulator, where the system never launches crash reporter extensions.
@main
struct ${typeName} {
  static func main() {}
}
#endif
`;
}
