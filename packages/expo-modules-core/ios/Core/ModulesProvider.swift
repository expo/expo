import Foundation

/**
 The native exports of one npm package that are declared with the Expo Modules API 2.0 macros: its modules
 and shared object classes. A modules provider returns the packages keyed by the npm package name, and that name
 is the JS name of the package, for example `expo.packages['expo-audio'].AudioPlayer`.
 Local and inline modules are in the `$local` package.
 */
public struct ExpoPackage {
  /**
   Name of the package of local and inline modules. It can't be the name of an npm package.
   */
  public static let localPackageName = "$local"

  /**
   Returns the packages in the order to register them: the npm packages by name, then the local package.
   The module registered last wins when two modules have the same name, so the app's own modules win,
   and the result is the same on every launch.
   */
  static func inRegistrationOrder(_ packages: [String: ExpoPackage]) -> [(name: String, package: ExpoPackage)] {
    return packages
      .map { (name: $0.key, package: $0.value) }
      .sorted { lhs, rhs in
        if (lhs.name == localPackageName) != (rhs.name == localPackageName) {
          return rhs.name == localPackageName
        }
        return lhs.name < rhs.name
      }
  }

  /**
   Module classes of the package.
   */
  public let modules: [AnyModule.Type]

  /**
   Shared object classes of the package. They are exported next to the modules, not as members of a module.
   */
  public let sharedObjects: [SharedObject.Type]

  public init(modules: [AnyModule.Type] = [], sharedObjects: [SharedObject.Type] = []) {
    self.modules = modules
    self.sharedObjects = sharedObjects
  }
}

/**
 Swift protocol defining the requirements for modules providers.
 */
public protocol ModulesProviderProtocol {
  typealias ExpoModuleTupleType = (module: AnyModule.Type, name: String?)

  /**
   The packages that provide modules declared with the Expo Modules API 2.0 macros, keyed by the npm package name.
   */
  var packages: [String: ExpoPackage] { get }

  /**
   Returns the module classes that don't use the Expo Modules API 2.0 macros.
   */
  func getModuleClasses() -> [ExpoModuleTupleType]

  /**
   Returns an array of classes that hooks into `ExpoAppDelegate` to receive app delegate events.
   */
  func getAppDelegateSubscribers() -> [ExpoAppDelegateSubscriber.Type]

  typealias ExpoReactDelegateHandlerTupleType = (packageName: String, handler: ExpoReactDelegateHandler.Type)
  /**
   Returns an array of `ExpoReactDelegateHandlerTupleType` for `ReactDelegate` to hook React instance creation.
   */
  func getReactDelegateHandlers() -> [ExpoReactDelegateHandlerTupleType]

  func getAppCodeSignEntitlements() -> AppCodeSignEntitlements
}

public extension ModulesProviderProtocol {
  /**
   Providers that conform to the protocol directly, without inheriting from `ModulesProvider`, have no packages by default.
   */
  var packages: [String: ExpoPackage] {
    return [:]
  }
}

/**
 The default implementation for modules provider.
 The proper implementation is generated by autolinking as part of `pod install` command.
 */
@objc
open class ModulesProvider: NSObject, ModulesProviderProtocol {
  public override required init() {}

  open var packages: [String: ExpoPackage] {
    return [:]
  }

  open func getModuleClasses() -> [ExpoModuleTupleType] {
    return []
  }

  open func getAppDelegateSubscribers() -> [ExpoAppDelegateSubscriber.Type] {
    return []
  }

  open func getReactDelegateHandlers() -> [ExpoReactDelegateHandlerTupleType] {
    return []
  }

  open func getAppCodeSignEntitlements() -> AppCodeSignEntitlements {
    return AppCodeSignEntitlements()
  }
}
