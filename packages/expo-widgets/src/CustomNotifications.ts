import { UnavailabilityError, uuid } from 'expo';
import { Platform } from 'react-native';

import type {
  CustomNotificationComponent,
  CustomNotificationOptions,
  CustomNotificationUpdateOptions,
  NativeCustomNotification,
  NativeCustomNotificationFactory,
} from './CustomNotifications.types';
import ExpoWidgetsModule from './ExpoWidgets';

/**
 * A posted custom notification. It wraps a native object that knows the notification key, so an
 * instance recovered with `CustomNotificationFactory.get()` or `getActive()` after a process restart
 * behaves like the one returned by `post()`.
 * @platform android
 */
export class CustomNotification<T extends object = object> {
  /** @hidden */
  private readonly nativeNotification: NativeCustomNotification;

  /** @hidden */
  constructor(nativeNotification: NativeCustomNotification) {
    this.nativeNotification = nativeNotification;
  }

  /**
   * The key of the notification, as passed to or generated by `post()`.
   */
  get id(): string {
    return this.nativeNotification.getId();
  }

  /**
   * Reads the props currently shown by the notification from the active notification, so they
   * include changes made by button presses inside the notification.
   *
   * Rejects when the notification is no longer active, for example after dismissal or cancellation.
   * @returns A promise that resolves to the current props.
   */
  async getProps(): Promise<T> {
    return (await this.nativeNotification.getProps()) as T;
  }

  /**
   * Renders the layout with new props and replaces the notification in place. The notification
   * does not alert again when `alertOnlyOnce` is `true`.
   *
   * Rejects when the notification is no longer active, for example after the user dismissed it or
   * after `cancel()`, or when it is cancelled while the update is rendering. Post it again in that case.
   * @param props The new props for the layout function.
   * @param options Presentation options to change. Options that are omitted keep their previous value.
   */
  update(props: T, options: CustomNotificationUpdateOptions = {}): Promise<void> {
    return this.nativeNotification.update(props as Record<string, any>, toNativeOptions(options));
  }

  /**
   * Removes the notification from the shade immediately.
   * Cancels any pending post or update for this notification.
   */
  cancel(): Promise<void> {
    return this.nativeNotification.cancel();
  }
}

/**
 * Posts and manages custom notifications that share one layout.
 * @platform android
 */
export class CustomNotificationFactory<T extends object = object> {
  /**
   * The name passed to `createCustomNotification()`.
   */
  readonly name: string;
  /** @hidden */
  private readonly nativeFactory: NativeCustomNotificationFactory | null;

  /** @hidden */
  constructor(name: string, layout: CustomNotificationComponent<T>) {
    this.name = name;
    this.nativeFactory =
      Platform.OS === 'android'
        ? new ExpoWidgetsModule.CustomNotificationFactory(name, layout as unknown as string)
        : null;
  }

  /**
   * Renders the layout and posts the notification. Posting with the `id` of an active notification
   * replaces that notification in place.
   *
   * Rejects when notifications are disabled for the app, when `channelId` names a channel that
   * does not exist, when the layout returns no `collapsed` section, or when the post is cancelled
   * before rendering finishes.
   * @param props The props for the layout function.
   * @param options Presentation options.
   * @returns A promise that resolves to a handle for the posted notification.
   */
  async post(props: T, options: CustomNotificationOptions = {}): Promise<CustomNotification<T>> {
    const nativeFactory = this.requireNativeFactory('post');
    const id = options.id ?? uuid.v4();
    const nativeNotification = await nativeFactory.post(
      id,
      props as Record<string, any>,
      toNativeOptions({
        ...options,
        ongoing: options.ongoing ?? false,
        alertOnlyOnce: options.alertOnlyOnce ?? true,
      })
    );
    return new CustomNotification<T>(nativeNotification);
  }

  /**
   * Returns the active notification with the given key.
   * @param id The key passed to or generated by `post()`.
   * @returns A promise that resolves to the notification, or to `null` when no such notification is active.
   */
  async get(id: string): Promise<CustomNotification<T> | null> {
    const nativeNotification = await this.requireNativeFactory('get').get(id);
    return nativeNotification ? new CustomNotification<T>(nativeNotification) : null;
  }

  /**
   * Returns every active notification posted with this layout, including notifications posted
   * before a process restart.
   */
  async getActive(): Promise<CustomNotification<T>[]> {
    const nativeNotifications = await this.requireNativeFactory('getActive').getActive();
    return nativeNotifications.map(
      (nativeNotification) => new CustomNotification<T>(nativeNotification)
    );
  }

  /**
   * Removes every active notification posted with this layout and cancels pending posts and updates.
   */
  async cancelAll(): Promise<void> {
    await this.requireNativeFactory('cancelAll').cancelAll();
  }

  private requireNativeFactory(methodName: string): NativeCustomNotificationFactory {
    if (!this.nativeFactory) {
      throw new UnavailabilityError('ExpoWidgets', `CustomNotificationFactory.${methodName}`);
    }
    return this.nativeFactory;
  }
}

/**
 * Creates a factory that posts notifications rendered from the given layout.
 *
 * The factory can be created on every platform. Its methods reject with `UnavailabilityError` on
 * platforms other than Android.
 * @param name A unique name for the layout. It identifies the layout when a notification button
 * is pressed and when active notifications are recovered.
 * @param layout The layout component, marked with the `'widget'` directive.
 * @example
 * ```tsx
 * import { Row, Text } from '@expo/ui/jetpack-compose';
 * import { createCustomNotification } from 'expo-widgets';
 *
 * type Props = { status: string };
 *
 * const OrderNotification = createCustomNotification('OrderNotification', (props: Props) => {
 *   'widget';
 *   return {
 *     collapsed: (
 *       <Row>
 *         <Text>{props.status}</Text>
 *       </Row>
 *     ),
 *   };
 * });
 *
 * const order = await OrderNotification.post({ status: 'Preparing' }, { id: 'order-1', ongoing: true });
 * await order.update({ status: 'Delivered' }, { ongoing: false, timeoutAfter: 15 * 60 * 1000 });
 * ```
 * @platform android
 */
export function createCustomNotification<T extends object = object>(
  name: string,
  layout: CustomNotificationComponent<T>
): CustomNotificationFactory<T> {
  return new CustomNotificationFactory<T>(name, layout);
}

// Strip omitted values so native updates preserve the previous options.
function toNativeOptions(options: CustomNotificationOptions): CustomNotificationUpdateOptions {
  const { id: _id, ongoing, autoCancel, ...rest } = options;
  return Object.fromEntries(
    Object.entries({
      ...rest,
      ongoing,
      autoCancel: autoCancel ?? (ongoing === undefined ? undefined : !ongoing),
    }).filter(([, value]) => value !== undefined)
  );
}
