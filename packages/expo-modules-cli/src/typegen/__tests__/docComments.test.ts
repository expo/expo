import { preserveDocComments } from '../docComments';

const FILE = '/pkg/src/native.types.ts';

const HEADER = `// @generated by expo-modules-cli. Edit only the doc comments by hand.
// Regenerate with \`expo-modules generate-types\`.

import type { SharedObject } from 'expo';
`;

function generated(body: string): string {
  return `${HEADER}\n${body}`;
}

describe(preserveDocComments, () => {
  it('keeps the comments of declarations and members, and adds new members without one', () => {
    const previous = generated(`/**
 * Plays a video.
 */
export declare class Player extends SharedObject {
  /**
   * The playback volume, from 0 to 1.
   */
  volume: number;
  /** Starts playback. */
  play(): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  volume: number;
  play(): void;
  pause(): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`/**
 * Plays a video.
 */
export declare class Player extends SharedObject {
  /**
   * The playback volume, from 0 to 1.
   */
  volume: number;
  /** Starts playback. */
  play(): void;
  pause(): void;
}
`)
    );
  });

  it('matches enum cases, record properties, constructors, static members, and events by name', () => {
    const previous = generated(`/** How to encode. */
export enum Encoding {
  /** Hexadecimal digits. */
  HEX = 'hex',
  BASE64 = 'base64',
}

export type Options = {
  /** The encoding of the result. */
  encoding?: Encoding;
  /** The bytes to hash. */
  length: number;
};

export type PlayerEvents = {
  /** Fires when the status changes. */
  onStatus(payload: string): void;
};

export declare class Player extends SharedObject<PlayerEvents> {
  /** Native code creates players. */
  private constructor();
  /** Creates a player with the default options. */
  static make(): Player;
  /** Copies this player. */
  make(): Player;
}
`);
    const source = generated(`export enum Encoding {
  BASE64 = 'base64',
  HEX = 'hex',
}

export type Options = {
  length: number;
  encoding?: Encoding;
};

export type PlayerEvents = {
  onStatus(payload: string): void;
};

export declare class Player extends SharedObject<PlayerEvents> {
  make(): Player;
  static make(): Player;
  private constructor();
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`/** How to encode. */
export enum Encoding {
  BASE64 = 'base64',
  /** Hexadecimal digits. */
  HEX = 'hex',
}

export type Options = {
  /** The bytes to hash. */
  length: number;
  /** The encoding of the result. */
  encoding?: Encoding;
};

export type PlayerEvents = {
  /** Fires when the status changes. */
  onStatus(payload: string): void;
};

export declare class Player extends SharedObject<PlayerEvents> {
  /** Copies this player. */
  make(): Player;
  /** Creates a player with the default options. */
  static make(): Player;
  /** Native code creates players. */
  private constructor();
}
`)
    );
  });

  it('keeps the comment of each overload when another overload is added', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(url: string): void;
  /** Loads a file. */
  load(file: number): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  load(data: ArrayBuffer): void;
  load(url: string): void;
  load(file: number): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`export declare class Player extends SharedObject {
  load(data: ArrayBuffer): void;
  /** Loads a URL. */
  load(url: string): void;
  /** Loads a file. */
  load(file: number): void;
}
`)
    );
  });

  it('pairs the overloads that changed in order, and warns about them', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(url: string): void;
  /** Loads a file. */
  load(file: number): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  load(url: string, headers: Record<string, string>): void;
  load(file: number): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      expect.objectContaining({ kind: 'changed', file: FILE, location: 'Player.load' }),
    ]);
    expect(result.source).toBe(
      generated(`export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(url: string, headers: Record<string, string>): void;
  /** Loads a file. */
  load(file: number): void;
}
`)
    );
  });

  it('keeps an unchanged overload without a comment out of the overloads that changed', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(url: string): void;
  load(file: number): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  load(file: number): void;
  load(url: string, headers: Record<string, string>): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      expect.objectContaining({ kind: 'changed', file: FILE, location: 'Player.load#2' }),
    ]);
    expect(result.source).toBe(
      generated(`export declare class Player extends SharedObject {
  load(file: number): void;
  /** Loads a URL. */
  load(url: string, headers: Record<string, string>): void;
}
`)
    );
  });

  it('keeps the comments of event listeners when the events map is inlined into the class', () => {
    const previous = generated(`export type PlayerEvents = {
  /** Fires when the status changes. */
  onStatus(payload: string): void;
};

export declare class Player extends SharedObject<PlayerEvents> {
  /** Starts playback. */
  play(): void;
}
`);
    const source = generated(`export enum PlayerEvents {}

export declare class Player extends SharedObject<{
  onStatus(payload: string): void;
}> {
  play(): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`export enum PlayerEvents {}

export declare class Player extends SharedObject<{
  /** Fires when the status changes. */
  onStatus(payload: string): void;
}> {
  /** Starts playback. */
  play(): void;
}
`)
    );
  });

  it('re-indents comments to their symbol and accepts blank lines or a declaration after them', () => {
    const previous = generated(`export declare class Player extends SharedObject {
      /**
       * The playback volume.
       *
       *     player.volume = 0.5;
       */

  volume: number;
  /** Starts playback. */ play(): void;
  seek(time: number): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  volume: number;
  play(): void;
  seek(time: number): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`export declare class Player extends SharedObject {
  /**
   * The playback volume.
   *
   *     player.volume = 0.5;
   */
  volume: number;
  /** Starts playback. */
  play(): void;
  seek(time: number): void;
}
`)
    );
  });

  it('reads a file that a formatter rewrote', () => {
    const previous = generated(`export enum Encoding {
  /** Hexadecimal digits. */
  HEX = "hex",
}

export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(
    url: string,
    onProgress: (arg0: number) => void,
  ): Promise<Record<string, number>>;
}
`);
    const source = generated(`export enum Encoding {
  HEX = 'hex',
}

export declare class Player extends SharedObject {
  load(url: string, onProgress: (arg0: number) => void): Promise<Record<string, number>>;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([]);
    expect(result.source).toBe(
      generated(`export enum Encoding {
  /** Hexadecimal digits. */
  HEX = 'hex',
}

export declare class Player extends SharedObject {
  /** Loads a URL. */
  load(url: string, onProgress: (arg0: number) => void): Promise<Record<string, number>>;
}
`)
    );
  });

  it('explains a file it cannot parse', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  play(): void;
`);

    expect(() => preserveDocComments(previous, previous, FILE)).toThrow(
      /Could not read the doc comments of \/pkg\/src\/native\.types\.ts/
    );
  });

  it('warns about each comment whose symbol is gone, with the text of the comment', () => {
    const previous = generated(`/** Plays a video. */
export declare class Player extends SharedObject {
  /**
   * The playback volume.
   */
  volume: number;
  /** Starts playback. */
  play(): void;
}
`);
    const source = generated(`/** Plays a video. */
export declare class Player extends SharedObject {
  start(): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      expect.objectContaining({
        kind: 'dropped',
        file: FILE,
        location: 'Player.volume',
        comment: '/**\n * The playback volume.\n */',
      }),
      expect.objectContaining({
        kind: 'dropped',
        file: FILE,
        location: 'Player.play',
        comment: '/** Starts playback. */',
      }),
    ]);
    expect(result.source).not.toContain('Starts playback');
  });

  it('warns about every comment when nothing is generated anymore', () => {
    const previous = generated(`/** Plays a video. */
export declare class Player extends SharedObject {
  /** Starts playback. */
  play(): void;
}
`);

    const result = preserveDocComments(null, previous, FILE);

    expect(result.source).toBeNull();
    expect(result.warnings.map((warning) => `${warning.kind} ${warning.location}`)).toEqual([
      'dropped Player',
      'dropped Player.play',
    ]);
  });

  it('warns about a comment above no declaration or member', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  seek(
    /** In seconds. */
    time: number
  ): void;
  /** Nothing follows. */
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  seek(time: number): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      expect.objectContaining({
        kind: 'dropped',
        file: FILE,
        location: 'line 8',
        comment: '/** In seconds. */',
      }),
      expect.objectContaining({
        kind: 'dropped',
        file: FILE,
        location: 'line 11',
        comment: '/** Nothing follows. */',
      }),
    ]);
    expect(result.source).toBe(source);
  });

  it('warns about a comment that follows code on its line instead of moving it to the next member', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  volume: number; /** From 0 to 1. */
  play(): void;
}
`);
    const source = generated(`export declare class Player extends SharedObject {
  volume: number;
  play(): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      expect.objectContaining({
        kind: 'dropped',
        file: FILE,
        location: 'line 7',
        comment: '/** From 0 to 1. */',
      }),
    ]);
    expect(result.source).toBe(source);
  });

  it('writes the comments of a file with CRLF line endings with LF line endings', () => {
    const previous = generated(`export declare class Player extends SharedObject {
  /**
   * Starts playback.
   */
  play(): void;
}
`).replace(/\n/g, '\r\n');
    const source = generated(`export declare class Player extends SharedObject {
  play(): void;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.source).toBe(previous.replace(/\r\n/g, '\n'));
  });

  it('warns when a commented member or one-line declaration changed, but not a class heading', () => {
    const previous = generated(`/** A file or a URL. */
export type Source = string;

/** Plays a video. */
export declare class Player extends SharedObject {
  /** The playback volume. */
  volume: number;
  /** Starts playback. */
  play(): void;
}
`);
    const source = generated(`export type Source = string | number;

export declare class Player extends SharedObject<PlayerEvents> {
  volume: number;
  play(): Promise<void>;
}
`);

    const result = preserveDocComments(source, previous, FILE);

    expect(result.warnings).toEqual([
      {
        kind: 'changed',
        file: FILE,
        location: 'Source',
        message: 'the declaration changed, so check that its doc comment is still accurate',
      },
      expect.objectContaining({ kind: 'changed', file: FILE, location: 'Player.play' }),
    ]);
  });
});
